#!/usr/bin/env python3
"""routeinv_gen.py -- write the route-invalidation workloads of perf follow-up I (Legion staticChanged and its route
index, src/sim/legion_routebins.h).

    python3 tools/scenarios/perf/routeinv_gen.py [OUTDIR]     (default: this file's directory)

Deterministic (no clock, no random module): the same script writes the same files byte for byte. Each file is one of
the scale suite's independent-destination layouts (tools/scenarios/scale/gen_scale.py: scatter -- every body its own
selection and destination, many -- squads of 25 with their own destinations) with static churn added: a grid of
spatially separated spots, each a 3 x 3 blocking feature placed and lifted again on its own period (5..19 ticks,
staggered starts), as structures built and destroyed or blocking wrecks appearing and clearing would. So nearly every
tick brings one or two small static changes far apart, while hundreds to thousands of groups hold routes: the case
the route index is for. Written as NAME.scn.gz: tools/we_timing.sh runs them as situations (--sitdir this directory;
the `L-` prefix selects Legion); for legion_scenario itself, zcat one to a .scn first.

  L-routeinv-scatter-2500   2500 groups (one body each), 4 x 4 churn spots   (the many-groups case)
  L-routeinv-scatter-10000  10000 groups, 6 x 6 churn spots                  (the extreme)
  L-routeinv-many-2500      100 groups (squads of 25), 4 x 4 churn spots      (few groups: must not regress)
  L-routeinv-local-5000     5000 groups patrolling 40 cells, 6 x 6 churn spots (local routes: a change reaches few)
  L-routeinv-local-10000    10000 groups patrolling 40 cells, 6 x 6 churn spots

Measurement scripts beside it: routeinv_ab.sh / routeinv_ab.py (timing pairs on the reserved cores, SIMPHASE and the
LPROBE syncStatic / staticChanged sums) and routeinv_pmu.sh / routeinv_pmu.py (instructions per phase, base vs
candidate vs the candidate's walk of every group).
"""
import gzip
import math
import os
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))


def lcg_perm(k, seed=12345):
    """gen_scale.py's fixed permutation of range(k) with no fixed point."""
    a = list(range(k))
    x = seed
    for i in range(k - 1, 0, -1):
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        j = x % (i + 1)
        a[i], a[j] = a[j], a[i]
    for i in range(k):
        if a[i] == i:
            j = (i + 1) % k
            a[i], a[j] = a[j], a[i]
    return a


def header(name, ticks, w, h):
    return ["scn 1", f"name {name}", f"ticks {ticks}", "seed 7", "players 2", "team 1 0", "weapons off",
            f"map flat {w} {h}", "type r roster"]


def churn_grid(w, h, k):
    """k x k spots over the map, each a 3 x 3 feature toggled on its own period from a staggered start."""
    lines = []
    for i in range(k):
        for j in range(k):
            x = 16 + (2 * i + 1) * (w - 32) // (2 * k)
            z = 16 + (2 * j + 1) * (h - 32) // (2 * k)
            s = i * k + j
            period = 5 + (s * 7) % 15
            lines.append(f"churn {x} {z} 3 3 every={period} toggle from={200 + 3 * s}")
    return lines


def write(name, lines, doc):
    """NAME.scn.gz, as tools/we_timing.sh reads situations (gzip without a name or time: byte-identical reruns)."""
    text = "# " + doc.replace("\n", "\n# ") + "\n# Generated by routeinv_gen.py -- edit the generator, not this file.\n"
    text += "\n".join(lines) + "\n"
    with open(os.path.join(OUT, name + ".scn.gz"), "wb") as f:
        with gzip.GzipFile(filename="", mode="wb", fileobj=f, mtime=0) as z:
            z.write(text.encode())


def scatter(n, spots, ticks):
    """gen_scale.py's scatter-n: n bodies, each its own selection clicked to its own distant destination over the
    first 600 ticks (two allied players); plus the churn grid."""
    pitch = 8
    g = int(math.ceil(math.sqrt(n)))
    w = h = g * pitch + 32
    perm = lcg_perm(n, seed=777)
    name = f"L-routeinv-scatter-{n}"
    L = header(name, ticks, w, h)
    orders = []
    for i in range(n):
        gx, gz = i % g, i // g
        x0, z0 = 16 + gx * pitch + 2, 16 + gz * pitch + 2
        L.append(f"group B{i} {i % 2} r 1 rect {x0} {z0} {x0 + 4} {z0 + 4}")
        j = perm[i]
        if abs(j % g - gx) + abs(j // g - gz) < g // 3:
            j = (g - 1 - gx) + g * min(g - 1, (g - 1 - gz))
            if j >= n:
                j = n - 1 - i % max(1, g)
        dx, dz = 16 + (j % g) * pitch + 4, 16 + (j // g) * pitch + 4
        orders.append((2 + (i * 600) // n, i, dx, dz))
    L += churn_grid(w, h, spots)
    for t, i, dx, dz in sorted(orders):
        L.append(f"at {t} move B{i} {dx} {dz}")
    write(name, L, f"{name}: {n} bodies, each its own selection clicked to its own distant destination over the first\n"
          f"600 ticks (scale suite scatter-{n}), with {spots} x {spots} spatially separated churn spots (3 x 3 blocking\n"
          "features toggled every 5..19 ticks from tick 200): many routes, small far-apart static changes every tick.")


def many(n, spots, ticks):
    """gen_scale.py's many-n: n/25 squads of 25, each clicked to its own distant tile; plus the churn grid."""
    squad, tile = 25, 40
    k = n // squad
    g = int(math.ceil(math.sqrt(k)))
    w = h = g * tile + 32
    perm = lcg_perm(k)
    name = f"L-routeinv-many-{n}"
    L = header(name, ticks, w, h)
    orders = []
    for i in range(k):
        gx, gz = i % g, i // g
        x0, z0 = 16 + gx * tile + 10, 16 + gz * tile + 10
        L.append(f"group S{i} {i % 2} r {squad} rect {x0} {z0} {x0 + 20} {z0 + 20}")
        j = perm[i]
        if abs(j % g - gx) + abs(j // g - gz) < g // 3:
            j = (g - 1 - gx) + g * min(g - 1, (g - 1 - gz))
            if j >= k:
                j = k - 1 - i % max(1, g)
        dx, dz = 16 + (j % g) * tile + 20, 16 + (j // g) * tile + 20
        orders.append((2 + (i * 600) // k, i, dx, dz))
    L += churn_grid(w, h, spots)
    for t, i, dx, dz in sorted(orders):
        L.append(f"at {t} move S{i} {dx} {dz}")
    write(name, L, f"{name}: {k} squads of {squad}, each clicked to its own distant tile over the first 600 ticks (scale\n"
          f"suite many-{n}), with {spots} x {spots} spatially separated churn spots (3 x 3 blocking features toggled every\n"
          "5..19 ticks from tick 200): few groups, the same churn (the ordinary case).")


def local(n, spots, ticks):
    """n bodies on scatter's grid, each its own selection patrolling to a point 40 cells away (one of eight directions,
    by body) over the first 300 ticks: many independent routes, each local (a bounded window of about 100 x 70
    cells), so a static change reaches few of them; plus the churn grid."""
    pitch = 8
    g = int(math.ceil(math.sqrt(n)))
    w = h = g * pitch + 32
    name = f"L-routeinv-local-{n}"
    L = header(name, ticks, w, h)
    dirs = [(40, 0), (28, 28), (0, 40), (-28, 28), (-40, 0), (-28, -28), (0, -40), (28, -28)]
    orders = []
    for i in range(n):
        gx, gz = i % g, i // g
        x0, z0 = 16 + gx * pitch + 2, 16 + gz * pitch + 2
        L.append(f"group B{i} {i % 2} r 1 rect {x0} {z0} {x0 + 4} {z0 + 4}")
        dx, dz = dirs[(i * 3 + gz) % 8]
        tx, tz = min(w - 12, max(12, x0 + 2 + dx)), min(h - 12, max(12, z0 + 2 + dz))
        orders.append((2 + (i * 300) // n, i, tx, tz))
    L += churn_grid(w, h, spots)
    for t, i, tx, tz in sorted(orders):
        L.append(f"at {t} patrol B{i} {tx} {tz}")
    write(name, L, f"{name}: {n} bodies, each its own selection patrolling to a point 40 cells away over the first 300\n"
          f"ticks, with {spots} x {spots} spatially separated churn spots (3 x 3 blocking features toggled every 5..19\n"
          "ticks from tick 200): many routes, each local, so a static change reaches few of them.")


scatter(2500, 4, 3000)
scatter(10000, 6, 3000)
many(2500, 4, 3000)
local(5000, 6, 3000)
local(10000, 6, 3000)
