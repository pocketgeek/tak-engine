#!/usr/bin/env python3
"""gen_legion100.py -- write the ~100-body versions of the Legion known-weakness fixtures.

    python3 tools/scenarios/legion100/gen_legion100.py

Deterministic. Each hand fixture is the parent fixture in tools/scenarios/ with its map, shapes and probes kept
and only the groups (and their orders) rescaled to about 100 bodies; the scale-family rows are written by
tools/scenarios/scale/gen_scale.py's own functions at N=100 (plus idle-50x50, 50 movers through 50 idle).
Triage of 2026-10-19 (Legion at reasonable unit counts); the parent's own header comment applies.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCN = os.path.dirname(HERE)


def rect_cells(x0, z0, cols, rows, px, pz):
    return " ".join(f"{x0 + c * px},{z0 + r * pz}" for r in range(rows) for c in range(cols))


def derive(parent, name, groups, orders, extra=(), note=""):
    """Copy PARENT.scn, drop its group/at lines, rename it, insert GROUPS and ORDERS."""
    out = [f"# {name}: ~100-body version of {parent}.scn ({note}). Generated by gen_legion100.py."]
    for ln in open(os.path.join(SCN, parent + ".scn")):
        ln = ln.rstrip("\n")
        if ln.startswith("group ") or ln.startswith("at "):
            continue
        if ln.startswith("name "):
            ln = f"name {name}"
        out.append(ln)
    out += list(extra) + list(groups) + list(orders)
    with open(os.path.join(HERE, name + ".scn"), "w") as f:
        f.write("\n".join(out) + "\n")


def main():
    # Corner lane order: one click of 100, and four clicks of 25 a tick apart (corner-8x56's shape).
    derive("corner-1x448", "corner-1x100", ["group A 0 m 100 rect 4 90 34 120 pitch=3"],
           ["at 1 move A 190 25"], note="one click of 100")
    derive("corner-8x56", "corner-4x25",
           ["group A 0 m 25 rect 4 90 19 105 pitch=3", "group B 0 m 25 rect 22 90 37 105 pitch=3",
            "group C 0 m 25 rect 4 108 19 123 pitch=3", "group D 0 m 25 rect 22 108 37 123 pitch=3"],
           [f"at {i + 1} move {g} 190 25" for i, g in enumerate("ABCD")], note="four clicks of 25")
    # Gaps and the strait.
    for g in ("gap10", "gap20"):
        derive(g, g + "-100", ["group A 0 m 100 rect 30 90 60 120 pitch=3"], ["at 1 move A 150 110"],
               note="100 bodies, 10x10 block")
    derive("strait-2x150", "strait-2x100", ["group B 0 b 100 rect 6 16 45 52 pitch=3"], ["at 1 move B 150 52"],
           note="100 boats")
    derive("island-1x150", "island-1x100", ["group U 0 u 100 cells " + rect_cells(30, 48, 10, 10, 3, 3)],
           ["at 1 move U 172 70"], note="100 bodies")
    # Walls.
    derive("attackring-wall-64", "attackring-wall-100",
           ["group A 0 a 100 rect 18 70 38 90 pitch=2 weapons=on", "group T 1 tgt 1 cells 130,80 weapons=off"],
           ["at 1 attack A @T"], note="100 attackers")
    for g, goal in (("doorplug-112", 112), ("doorplug-124", 124)):
        derive(g, g.replace("doorplug", "doorplug100"),
               ["group A 0 m 50 cells " + rect_cells(14, 36, 10, 5, 3, 4),
                "group B 0 m 50 cells " + rect_cells(14, 64, 10, 5, 3, 4)],
               [f"at 1 move A {goal} 50", "at 3001 move B 200 50"], note="two groups of 50")
    # Tails.
    derive("ringcross", "ringcross-100",
           ["group A 0 a 50 rect 100 70 124 94 pitch=2 weapons=on", "group T 1 tgt 1 cells 160,80 weapons=off",
            "group M 0 m 50 rect 12 62 42 98 pitch=3"],
           ["at 1 attack A @T", "at 1500 move M 235 80"], note="50 attackers, 50 movers")
    types = ["araarch", "araking", "arasmith", "crechie", "cretort", "lifwolf", "npcayla", "npcduma", "npchunt",
             "npcpeas2", "npcshop", "tarfire"]
    groups, orders = [], []
    k = 0
    for row in range(13):
        for col in range(4):
            for side in (0, 1):
                if k >= 100:
                    break
                x = (44 + col * 4) if side == 0 else (212 - col * 4)
                z = 104 + row * 4
                groups.append(f"group u{k:02d} 0 {types[k % len(types)]} 1 cells {x},{z}")
                orders.append(f"at 1 move u{k:02d} {216 if side == 0 else 40} 128")
                k += 1
    derive("motion-cross", "motion-cross-100", groups, orders, note="50 fbi bodies a side, one click each")
    # Lifted flyers: 100 walkers past 12 idle own flyers, and the control without flyers.
    derive("liftstream", "liftstream-100",
           ["group F 0 f 12 rect 70 46 82 58 pitch=3", "group G 0 m 100 rect 20 34 50 64 pitch=3"],
           ["at 90 move G 160 50"], note="100 walkers, 12 own idle flyers")
    derive("liftstream", "liftstream-100-open", ["group G 0 m 100 rect 20 34 50 64 pitch=3"],
           ["at 90 move G 160 50"], note="control: no flyers")
    # Scale families at N=100.
    sys.path.insert(0, os.path.join(SCN, "scale"))
    import gen_scale
    gen_scale.OUT = HERE
    for fn in (gen_scale.swap, gen_scale.bridges, gen_scale.maze, gen_scale.idle, gen_scale.churn,
               gen_scale.scatter, gen_scale.attack, gen_scale.mixed):
        fn(100)
    # idle-50x50: half the bodies move through the other half standing idle.
    s, sm = gen_scale.side(50), gen_scale.side(50)
    h, w = s + 128, s + 2 * sm + 256
    xi = sm + 96
    L = gen_scale.header("idle-50x50", gen_scale.ticks_for(w), w, h)
    L += ["type r roster", f"group I 0 r 50 rect {xi} 64 {xi + s} {64 + s}",
          f"group M 0 r 50 rect 16 {(h - sm) // 2} {16 + sm} {(h - sm) // 2 + sm}",
          f"at 2 move M {w - 16 - sm // 2} {h // 2}"]
    gen_scale.write("idle-50x50", L, "idle-50x50: 50 movers sent through a block of 50 idle bodies.")


if __name__ == "__main__":
    main()
